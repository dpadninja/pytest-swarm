# Combined with @pytest.mark.parametrize
# ---------------------------------------------------------------------------

class TestCombinedWithMark:
    """pytest_generate_tests and @pytest.mark.parametrize together."""

    def test_cartesian_product_runs(self, pytester):
        """Cartesian product of pytest_generate_tests and @pytest.mark.parametrize runs."""
        pytester.makeconftest("""
def pytest_generate_tests(metafunc):
    if "x" in metafunc.fixturenames:
        metafunc.parametrize("x", [1, 2])
""")
        pytester.makepyfile("""
import pytest

@pytest.mark.swarm
@pytest.mark.parametrize("y", ["a", "b"])
def test_items(x, y):
    assert x in (1, 2)
    assert y in ("a", "b")
""")
        # 2 x values × 2 y values = 4 items
        pytester.runpytest().assert_outcomes(passed=4)

    def test_cartesian_product_values_correct(self, pytester, tmp_path):
        """Every (x, y) combination is seen exactly once."""
        log = tmp_path / "log.txt"
        pytester.makeconftest(f"""
def pytest_generate_tests(metafunc):
    if "x" in metafunc.fixturenames:
        metafunc.parametrize("x", [0, 1])
""")
        pytester.makepyfile(f"""
import pytest

@pytest.mark.swarm
@pytest.mark.parametrize("y", ["a", "b"])
def test_items(x, y):
    with open({str(log)!r}, "a") as f:
        f.write(f"{{x}}{{y}}\\n")
""")
        pytester.runpytest().assert_outcomes(passed=4)
        assert sorted(_read(log)) == ["0a", "0b", "1a", "1b"]


