"""Compatibility tests for pytest_generate_tests hook with pytest-swarm."""

from __future__ import annotations

import pytest


# ---------------------------------------------------------------------------
# Helpers shared across tests
# ---------------------------------------------------------------------------

def _read(path) -> list[str]:
    return path.read_text().splitlines() if path.exists() else []


# ---------------------------------------------------------------------------
# Direct (non-indirect) parametrization — parallel full path
# ---------------------------------------------------------------------------

class TestDirectParametrize:
    """pytest_generate_tests with non-indirect params → parallel full path."""

    def test_basic_params_run_and_pass(self, pytester):
        """Items generated by pytest_generate_tests are run and pass."""
        pytester.makeconftest("""
def pytest_generate_tests(metafunc):
    if "n" in metafunc.fixturenames:
        metafunc.parametrize("n", range(4))
""")
        pytester.makepyfile("""
import pytest

@pytest.mark.swarm
def test_items(n):
    assert n in range(4)
""")
        pytester.runpytest().assert_outcomes(passed=4)

    def test_values_forwarded_correctly(self, pytester, tmp_path):
        """Each generated parameter value is actually forwarded to the test body."""
        log = tmp_path / "seen.txt"
        pytester.makeconftest(f"""
def pytest_generate_tests(metafunc):
    if "val" in metafunc.fixturenames:
        metafunc.parametrize("val", ["x", "y", "z"])
""")
        pytester.makepyfile(f"""
import pytest

@pytest.mark.swarm
def test_items(val):
    with open({str(log)!r}, "a") as f:
        f.write(val + "\\n")
""")
        pytester.runpytest().assert_outcomes(passed=3)
        assert sorted(_read(log)) == ["x", "y", "z"]

    def test_conftest_generate_tests(self, pytester):
        """pytest_generate_tests defined in conftest (plugin-style) works."""
        pytester.makeconftest("""
def pytest_generate_tests(metafunc):
    if "idx" in metafunc.fixturenames:
        metafunc.parametrize("idx", [10, 20, 30])
""")
        pytester.makepyfile("""
import pytest

@pytest.mark.swarm
def test_items(idx):
    assert idx in (10, 20, 30)
""")
        pytester.runpytest().assert_outcomes(passed=3)

    def test_all_items_collected_and_run(self, pytester, tmp_path):
        """All N generated items are collected and each runs exactly once."""
        log = tmp_path / "runs.txt"
        pytester.makeconftest(f"""
def pytest_generate_tests(metafunc):
    if "n" in metafunc.fixturenames:
        metafunc.parametrize("n", range(6))
""")
        pytester.makepyfile(f"""
import pytest

@pytest.mark.swarm
def test_items(n):
    with open({str(log)!r}, "a") as f:
        f.write(str(n) + "\\n")
""")
        pytester.runpytest().assert_outcomes(passed=6)
        assert sorted(int(x) for x in _read(log)) == list(range(6))


