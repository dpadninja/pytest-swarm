# ---------------------------------------------------------------------------
# Hook compatibility: public pytest hooks fire for generate_tests items
# ---------------------------------------------------------------------------

class TestHooksWithGenerateTests:
    """Public hooks must fire correctly for items from pytest_generate_tests."""

    def test_logreport_fires_for_all_phases(self, pytester, tmp_path):
        """pytest_runtest_logreport fires for setup/call/teardown for each item."""
        log = tmp_path / "log.txt"
        pytester.makeconftest(f"""
import pytest

@pytest.hookimpl
def pytest_runtest_logreport(report):
    with open({str(log)!r}, "a") as f:
        f.write(report.when + "\\n")

def pytest_generate_tests(metafunc):
    if "n" in metafunc.fixturenames:
        metafunc.parametrize("n", range(3))
""")
        pytester.makepyfile("""
import pytest

@pytest.mark.swarm
def test_items(n):
    pass
""")
        pytester.runpytest().assert_outcomes(passed=3)
        calls = _read(log)
        assert len(calls) == 9
        assert calls.count("setup") == 3
        assert calls.count("call") == 3
        assert calls.count("teardown") == 3

    def test_skip_works_with_generate_tests(self, pytester):
        """pytest.mark.skip is honoured for items from pytest_generate_tests."""
        pytester.makeconftest("""
def pytest_generate_tests(metafunc):
    if "n" in metafunc.fixturenames:
        metafunc.parametrize("n", range(3))
""")
        pytester.makepyfile("""
import pytest

@pytest.mark.swarm
@pytest.mark.skip(reason="skipped")
def test_items(n):
    pass
""")
        pytester.runpytest().assert_outcomes(skipped=3)

    def test_xfail_works_with_generate_tests(self, pytester):
        """pytest.mark.xfail is honoured for items from pytest_generate_tests."""
        pytester.makeconftest("""
def pytest_generate_tests(metafunc):
    if "n" in metafunc.fixturenames:
        metafunc.parametrize("n", range(3))
""")
        pytester.makepyfile("""
import pytest

@pytest.mark.swarm
@pytest.mark.xfail
def test_items(n):
    assert False
""")
        pytester.runpytest().assert_outcomes(xfailed=3)